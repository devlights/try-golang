package main

import "fmt"

func main() {
	//
	// 以下の２つは同じことになる
	//
	{
		for i := 0; i < 5; i++ {
			fmt.Println(i + 1)
		}
	}
	fmt.Println("----------------------")
	{
		//
		// Goで ^ は整数の全ビットを反転を意味する。
		// Goの整数は２の補数表現なので、以下が成り立つ。
		//
		// ^i = -i - 1
		//
		// したがって
		//
		// -^i = -(^i)
		//     = -(-i - 1)
		//     = i + 1
		//
		// ビット反転は他の言語（例えばC言語やPython)では ~i となる。
		// 普通に i+1 と書く方が分かりやすいし一目瞭然なのは言うまでもない。
		//
		for i := 0; i < 5; i++ {
			fmt.Println(-^i)
		}
	}
}
